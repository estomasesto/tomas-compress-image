async function processBatch(plugin, settings, files, onProgress, shouldAbort) {
  const result = {
    converted: 0,
    skippedSmall: 0,
    skippedAnimated: 0,
    errorPaths: [],
    bytesBefore: 0,
    bytesAfter: 0,
    durationMs: 0,
    cancelled: false
  };
  const startedAt = Date.now();
  for (let i = 0; i < files.length; i++) {
    if (shouldAbort == null ? void 0 : shouldAbort()) {
      result.cancelled = true;
      result.durationMs = Date.now() - startedAt;
      return result;
    }
    const file = files[i];
    try {
      const data = await plugin.app.vault.readBinary(file);
      if (settings.skipSmallFiles && data.byteLength < settings.skipThresholdKB * 1024) {
        result.skippedSmall++;
        onProgress(i + 1, files.length);
        continue;
      }
      const blob = new Blob([data], { type: `image/${file.extension}` });
      if (file.extension.toLowerCase() === "gif" && await isAnimatedGif(blob)) {
        result.skippedAnimated++;
        onProgress(i + 1, files.length);
        continue;
      }
      const out = await compressImage(blob, settings);
      const compressedBuffer = out.buffer;
      const beforeSize = data.byteLength;
      const afterSize = compressedBuffer.byteLength;
      const baseName = file.path.substring(0, file.path.lastIndexOf("."));
      let newPath = `${baseName}.${out.ext}`;
      let suffix = 1;
      while (newPath !== file.path && plugin.app.vault.getAbstractFileByPath(newPath)) {
        newPath = `${baseName} ${suffix}.${out.ext}`;
        suffix++;
      }
      await plugin.app.vault.modifyBinary(file, compressedBuffer);
      if (newPath !== file.path) {
        await plugin.app.fileManager.renameFile(file, newPath);
      }
      result.converted++;
      result.bytesBefore += beforeSize;
      result.bytesAfter += afterSize;
    } catch (err) {
      console.error(`Failed to process ${file.path}:`, err);
      result.errorPaths.push(file.path);
    }
    onProgress(i + 1, files.length);
  }
  result.durationMs = Date.now() - startedAt;
  return result;
}

